"""Rebuild the compact TMDB fallback. Standard library only; not run by app/build.

Usage: python3 scripts/build-demo-catalogue.py /absolute/path/movies_complete.csv
Source is pinned below; only factual gameplay fields are retained. Poster HEAD
verification is a separate, opt-in audit so normal development needs no network.
"""
import csv
import datetime
import json
import math
from pathlib import Path
import re
import sys

SOURCE = 'https://raw.githubusercontent.com/TjanMichela/Movie-Data-Analysis/84d01fcfb0b89f12ce445740fddac37270e4a042/movies_complete.csv'
COUNTRIES = dict(item.split(':') for item in (
    'United States of America:US|United Kingdom:GB|Germany:DE|France:FR|Canada:CA|Australia:AU|Italy:IT|Japan:JP|Spain:ES|China:CN|New Zealand:NZ|Hong Kong:HK|India:IN|Czech Republic:CZ|Ireland:IE|Russia:RU|Sweden:SE|Belgium:BE|United Arab Emirates:AE|Malta:MT|Switzerland:CH|Iceland:IS|Mexico:MX|Denmark:DK|South Africa:ZA|Taiwan:TW|Austria:AT|Brazil:BR|Peru:PE|Poland:PL|Hungary:HU|South Korea:KR|Indonesia:ID|Netherlands:NL|Bahamas:BS|Portugal:PT|Morocco:MA|Luxembourg:LU|Slovenia:SI|Norway:NO|Singapore:SG|Philippines:PH|Greece:GR|Bulgaria:BG|Finland:FI|Cambodia:KH|Thailand:TH|Argentina:AR|Romania:RO|Iran:IR|Turkey:TR|Serbia:RS|Vietnam:VN|Ukraine:UA|Pakistan:PK'
).split('|'))
records = {}
for r in csv.DictReader(open(sys.argv[1], encoding='utf-8')):
    try:
        film_id = int(r['id'])
        date = datetime.date.fromisoformat(r['release_date'])
        votes, popularity, runtime = int(float(r['vote_count'])), float(r['popularity']), int(float(r['runtime']))
        genres, cast = r['genres'].split('|'), r['cast'].split('|')[:5]
        countries = [COUNTRIES[c] for c in r['production_countries'].split('|')]
        poster = re.search(r'/([A-Za-z0-9_-]+\.jpg)', r['poster_path'])
    except (ValueError, KeyError):
        continue
    threshold = max(150, math.floor((250 if date.year < 1980 else 600 if date.year < 2000 else 1200) * (1 if r['original_language'] == 'en' else .65) + .5))
    if not (date <= datetime.date.today() and date.year >= 1888 and votes >= threshold and (popularity >= .5 or votes >= threshold * 2) and 60 <= runtime <= 360 and r['genres'] and 'TV Movie' not in genres and r['cast'] and r['director'] and countries and re.fullmatch('[a-z]{2}', r['original_language']) and poster):
        continue
    row = [film_id, r['title'], date.year, '/' + poster.group(1), runtime, r['director'].split('|')[0], genres, cast, r['belongs_to_collection'] or None, r['original_language'], countries, votes, round(popularity, 3)]
    # Recognition relative to age and voting audience, not current popularity alone.
    score = votes / threshold * (1 + math.log1p(popularity) * .02)
    records[film_id] = (score, row)
rows = [row for _, row in sorted(records.values(), key=lambda x: (-x[0], x[1][0]))[:1200]]
rows.sort(key=lambda row: row[0])
header = '''// Generated by scripts/build-demo-catalogue.py. TMDB-derived metadata snapshot.
// Source: ''' + SOURCE + '''
// See public/licenses/catalogue-source.txt and README for provenance/limitations.
import type { Movie } from "../game/types.ts";
type Row = [number,string,number,string,number,string,string[],string[],string|null,string,string[],number,number];
const rows: Row[] = [
'''
footer = '''];
export const SNAPSHOT_MOVIES: Movie[] = rows.map(([tmdbId,title,releaseYear,posterPath,runtime,director,genres,cast,collectionName,originalLanguage,productionCountries,voteCount,popularity]) => ({
  id: String(tmdbId), tmdbId, title, releaseYear, posterPath, runtime, director, genres, cast,
  collectionName, belongsToCollection: Boolean(collectionName), originalLanguage, productionCountries, voteCount, popularity,
}));
'''
out = Path(__file__).resolve().parents[1] / 'lib/data/catalogue-snapshot.ts'
out.write_text(header + ''.join(json.dumps(row,ensure_ascii=False,separators=(',',':'))+',\n' for row in rows) + footer, encoding='utf-8')
print(f'{len(rows)} films; {out.stat().st_size:,} bytes; source {SOURCE}')
