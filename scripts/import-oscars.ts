/** Offline only. Supply the pinned upstream file locally; never fetched by builds/runtime. */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { PRACTICE_CATALOGUE } from "../lib/data/catalogue.ts";
import { prepareOscarImport, SOURCE, SOURCE_URL } from "./awards/importer.ts";
import { FILM_REVIEWS } from "./awards/reviews.ts";

const path=process.argv[2];
if(!path) throw new Error("Usage: npm run prepare:oscars -- /path/to/oscar-nominations.json [--check]");
const raw=readFileSync(path);
if(createHash("sha256").update(raw).digest("hex")!==SOURCE.sha256)
  throw new Error("Source SHA-256 differs from the reviewed pin. Audit/update the source contract before importing.");
const {records,audit}=prepareOscarImport(JSON.parse(raw.toString("utf8")),PRACTICE_CATALOGUE,FILM_REVIEWS);
if(audit.reviewFailures.length) throw new Error(`Film review failed: ${JSON.stringify(audit.reviewFailures)}`);
const tuples=Object.entries(records).map(([id,r])=>[Number(id),r.oscarNominations,r.oscarWins,r.nominatedForBestPicture,r.wonBestPicture,r.awardsSource]);
const snapshot=`// Generated by scripts/import-oscars.ts. Only independently reviewed films.\n// MIT source notice: public/licenses/oscar-source.txt. See notes/oscar-coverage.md.\nimport type { OscarRecord } from "../game/types.ts";\nconst rows: [number,number,number,boolean,boolean,string][] = ${JSON.stringify(tuples,null,2)};\nexport const OSCAR_RECORDS: Readonly<Record<number, OscarRecord>> = Object.fromEntries(rows.map(([id,n,w,bp,bpw,source])=>[id,{\n  oscarNominations:n,oscarWins:w,nominatedForBestPicture:bp,wonBestPicture:bpw,\n  awardsDataStatus:"verified",awardsSource:source,verifiedOn:"${SOURCE.verifiedOn}",\n  verifiedThroughAwardYear:${SOURCE.throughAwardYear},coverageThroughCeremony:${SOURCE.throughCeremony},countingMethod:"competitive-film-category-entries",\n}]));\n`;
const outputs=new Map([
  ["lib/data/oscar-snapshot.ts",snapshot],
  ["notes/oscar-import-audit.json",JSON.stringify({...audit,sourceUrl:SOURCE_URL},null,2)+"\n"],
]);
for(const [file,content] of outputs) {
  if(process.argv.includes("--check")) {
    if(readFileSync(file,"utf8")!==content) throw new Error(`${file} is stale; regenerate and review it`);
  } else writeFileSync(file,content);
}
console.log(JSON.stringify(audit.summary,null,2));
