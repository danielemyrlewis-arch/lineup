/** Offline, deterministic verification. Builds only consume the resulting local snapshot. */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { PRACTICE_CATALOGUE } from "../lib/data/catalogue.ts";
import { OSCAR_RECORDS } from "../lib/data/oscar-snapshot.ts";
import { OSCAR_KEYS } from "../lib/data/awards.ts";
import { verifyWikidataCoverage } from "./awards/wikidata-verifier.ts";
import type { WikidataOscarInput } from "./awards/wikidata-types.ts";

// Updating a download does not approve it. Change this pin only after reviewing
// identity/category audits, boundary ceremonies, source rights and regressions.
export const VERIFIED_INPUT_SHA256="9c459b108a8cbfabd9c15776215371937c5aa945322bc9a7d3d152c51c1e1d01";
const raw=readFileSync("notes/oscar-wikidata-input.json");
if(createHash("sha256").update(raw).digest("hex")!==VERIFIED_INPUT_SHA256)
  throw new Error("Wikidata input differs from the reviewed pin; audit it before approving a new snapshot");
const input=JSON.parse(raw.toString("utf8")) as WikidataOscarInput;
const legacyRaw=readFileSync("notes/oscar-import-audit.json");
const legacyAuditSha256="2275047f6c61cff3d4c6c247642f441c47bdf9e2c12ac56ee1e2d30e573b3c65";
if(createHash("sha256").update(legacyRaw).digest("hex")!==legacyAuditSha256)
  throw new Error("Historical corroboration audit differs from the reviewed baseline");
const legacy=JSON.parse(legacyRaw.toString("utf8"));
const result=verifyWikidataCoverage(input,PRACTICE_CATALOGUE,legacy,OSCAR_RECORDS);
if(result.audit.conflicts.length)throw new Error(`Independent film evidence conflicts: ${JSON.stringify(result.audit.conflicts)}`);
if(!result.audit.bestPicture.winnerCoverage||!result.audit.bestPicture.nomineeCoverage)
  throw new Error("Best Picture completeness checks failed; do not publish negative category answers");
const rows=Object.entries(result.answers).map(([id,facts])=>{
  let yes=0,no=0,current=0;
  OSCAR_KEYS.forEach((key,index)=>{
    const fact=facts[key];if(!fact)return;
    if(fact.value)yes|=1<<index;else no|=1<<index;
    if(fact.coverageThroughCeremony===98)current|=1<<index;
  });
  const entity=result.audit.films.find(f=>f.tmdbId===Number(id))!.entity;
  return [Number(id),entity,yes,no,current];
});
const snapshot=`// Generated by scripts/prepare-oscar-coverage.ts from the pinned CC0 evidence.\n// Full provenance and category-completeness checks: notes/oscar-coverage-improvement.md.\nimport type { OscarRecord } from "../game/types.ts";\nimport { OSCAR_KEYS } from "./awards.ts";\nconst rows: [number,string,number,number,number][] = ${JSON.stringify(rows)};\nexport const OSCAR_QUESTION_EVIDENCE: Readonly<Record<number,NonNullable<OscarRecord["answers"]>>> = Object.fromEntries(rows.map(([id,qid,yes,no,current])=>{\n  const answers:NonNullable<OscarRecord["answers"]>={};\n  OSCAR_KEYS.forEach((key,index)=>{\n    const bit=1<<index;if(!((yes|no)&bit))return;\n    const year=(current&bit)?2025:2023;\n    answers[key]={value:!!(yes&bit),source:\x60https://www.wikidata.org/wiki/\x24{qid}\x60,verifiedOn:"${input.retrievedOn}",verifiedThroughAwardYear:year,coverageThroughCeremony:year-1927,\n      basis:key==="pictureNominated"||key==="pictureWon"?"complete-category":key==="nominations3"||key==="nominations5"||key==="wins3"?"minimum-count":"positive-entry"};\n  });\n  return [id,answers];\n}));\n`;
const audit={inputSha256:VERIFIED_INPUT_SHA256,legacyAuditSha256,...result.audit};
for(const [file,content] of [
  ["lib/data/oscar-question-snapshot.ts",snapshot],
  ["notes/oscar-question-coverage.json",JSON.stringify(audit,null,2)+"\n"],
]) {
  if(process.argv.includes("--check")) {
    if(readFileSync(file,"utf8")!==content)throw new Error(`${file} is stale`);
  } else writeFileSync(file,content);
}
console.log(JSON.stringify({identityVerified:audit.identityVerified,bestPictureNominees:audit.bestPicture.nominees,bestPictureWinners:audit.bestPicture.winners,
  categoryCoverageVerified:audit.bestPicture.nomineeCoverage&&audit.bestPicture.winnerCoverage,coverage:audit.coverage,distribution:audit.distribution,
  fullyUnknownFilms:audit.noKnownAnswers,exactTotals:audit.exactTotals,verifiedZeroNominations:audit.verifiedZeroNominations,
  corroboratedStatementGroups:audit.positiveEvidence.accepted.length},null,2));
