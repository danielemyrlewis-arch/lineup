"""Extract existing catalogue details from the matching public TMDB snapshot.
Usage: python3 scripts/build-details-snapshot.py movies_metadata.csv credits.csv
Pinned source: https://github.com/tima-chan/TheMovieDataBase/tree/77aaa72bff5e687ad496f5a579217b312352977e
Only IDs already in LINEUP are retained. No changes to selection or eligibility.
"""
import ast,csv,json,subprocess,sys
from pathlib import Path
csv.field_size_limit(2_000_000)
root=Path(__file__).resolve().parents[1]
needed=set(json.loads(subprocess.check_output(['node','--experimental-strip-types','--input-type=module','-e',"import {PRACTICE_CATALOGUE} from './lib/data/catalogue.ts'; console.log(JSON.stringify(PRACTICE_CATALOGUE.map(m=>m.tmdbId)))"],cwd=root)))
rows={}
for raw in csv.DictReader(open(sys.argv[1],encoding='utf-8')):
    try:
        film_id=int(raw['id'])
        if film_id not in needed:continue
        companies=ast.literal_eval(raw['production_companies'])
        companies=[[c['id'],c['name']] for c in companies] if isinstance(companies,list) and companies else None
        rows[film_id]=[film_id,raw['overview'].strip()[:1000] or None,companies,None]
    except (ValueError,SyntaxError,TypeError,KeyError):continue
for raw in csv.DictReader(open(sys.argv[2],encoding='utf-8')):
    try:
        film_id=int(raw['id'])
        if film_id not in rows:continue
        cast=ast.literal_eval(raw['cast'])
        cast.sort(key=lambda c:c.get('order') if isinstance(c.get('order'),int) and c['order']>=0 else sys.maxsize)
        if not cast or not cast[0].get('name'):continue
        lead=cast[0]
        # TMDB's current person record supersedes this known stale 2017 credit.
        # https://www.themoviedb.org/person/27578-elliot-page
        if lead.get('id') == 27578: lead={**lead,'name':'Elliot Page','gender':3}
        rows[film_id][3]=[lead.get('id'),lead['name'],lead.get('character') or None,{1:'female',2:'male',3:'nonbinary'}.get(lead.get('gender'))]
    except (ValueError,SyntaxError,TypeError,KeyError):continue
header='''// Generated by scripts/build-details-snapshot.py from TMDB movie details/credits.
// Pinned source: https://github.com/tima-chan/TheMovieDataBase/tree/77aaa72bff5e687ad496f5a579217b312352977e
// Values are historical; unknown gender is preserved, never inferred from names.
import type { Movie, LeadGender } from "../game/types.ts";
type Row = [number,string|null,[number,string][]|null,[number|null,string,string|null,LeadGender|null]|null];
const rows: Row[] = [
'''
footer='''];
export const SNAPSHOT_DETAILS: Readonly<Record<number,Pick<Movie,"overview"|"productionCompanies"|"topBilledLead">>> = Object.fromEntries(rows.map(([id,overview,companies,lead])=>[id,{
  overview, productionCompanies:companies?.map(([id,name])=>({id,name}))??null,
  topBilledLead:lead?{tmdbId:lead[0],name:lead[1],character:lead[2],gender:lead[3]}:null,
}]));
'''
out=root/'lib/data/details-snapshot.ts'
out.write_text(header+''.join(json.dumps(rows[k],ensure_ascii=False,separators=(',',':'))+',\n' for k in sorted(rows))+footer,encoding='utf-8')
print(json.dumps({'films':len(rows),'overview':sum(bool(r[1]) for r in rows.values()),'companies':sum(r[2] is not None for r in rows.values()),'lead':sum(r[3] is not None for r in rows.values()),'knownLeadGender':sum(r[3] is not None and r[3][3] is not None for r in rows.values()),'sourceBytes':out.stat().st_size}))
